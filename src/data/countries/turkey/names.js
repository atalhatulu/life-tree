export const UNISEX_NAMES=Object.freeze([...GIVEN_NAME_GROUPS.unisex]);
export const FIRST_NAMES=Object.freeze({
 female:Object.freeze([...GIVEN_NAME_GROUPS.female.common,...GIVEN_NAME_GROUPS.female.regular,...GIVEN_NAME_GROUPS.female.rare,...UNISEX_NAMES]),
 male:Object.freeze([...GIVEN_NAME_GROUPS.male.common,...GIVEN_NAME_GROUPS.male.regular,...GIVEN_NAME_GROUPS.male.rare,...UNISEX_NAMES])
});
export const SURNAMES=Object.freeze([...SURNAME_GROUPS.common,...SURNAME_GROUPS.regular,...SURNAME_GROUPS.rare]);

const TIERS=Object.freeze({common:5,regular:2,rare:1});
function weightedNames(groups){
 return Object.entries(TIERS).flatMap(([tier,weight])=>groups[tier].map(value=>({value,weight})));
}
const FIRST_NAME_OPTIONS={
 female:[...weightedNames(GIVEN_NAME_GROUPS.female),...UNISEX_NAMES.map(value=>({value,weight:2}))],
 male:[...weightedNames(GIVEN_NAME_GROUPS.male),...UNISEX_NAMES.map(value=>({value,weight:2}))]
};
const SURNAME_OPTIONS=weightedNames(SURNAME_GROUPS);

/** Avoid the names of close relatives without making a name impossible to draw. */
export function pickFirstName(rng,sex,{avoid=[]}={}){
 const options=FIRST_NAME_OPTIONS[sex];
 if(!options)throw new Error('Unknown name category: '+sex);
 const blocked=new Set(avoid.map(name=>String(name).toLocaleLowerCase('tr-TR')));
 const available=options.filter(item=>!blocked.has(item.value.toLocaleLowerCase('tr-TR')));
 return rng.weighted(available.length?available:options);
}

export function pickSurname(rng){
 return rng.weighted(SURNAME_OPTIONS);
}
